export function getHelpArticle(id: string): HelpArticle | undefined {
  return HELP_ARTICLES.find((article) => article.id === id);
}

export function searchHelpArticles(query: string): HelpArticle[] {
  const normalized = query.trim().toLowerCase();
  if (!normalized) return HELP_ARTICLES;

  return HELP_ARTICLES.filter((article) => {
    const haystack = [
      article.title,
      article.body,
      ...article.keywords,
      HELP_CATEGORY_LABELS[article.category],
    ]
      .join("\n")
      .toLowerCase();
    return haystack.includes(normalized);
  });
}

export function groupHelpArticlesByCategory(
  articles: HelpArticle[],
): Array<{ category: HelpCategory; label: string; articles: HelpArticle[] }> {
  return HELP_CATEGORY_ORDER.map((category) => ({
    category,
    label: HELP_CATEGORY_LABELS[category],
    articles: articles.filter((article) => article.category === category),
  })).filter((group) => group.articles.length > 0);
}
